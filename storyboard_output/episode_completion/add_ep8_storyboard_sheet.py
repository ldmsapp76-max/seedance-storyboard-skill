def copy_sheet_layout(src_ws, dst_ws):
    for col, dim in src_ws.column_dimensions.items():
        dst_ws.column_dimensions[col].width = dim.width
    for row_idx in range(1, 4):
        dst_ws.row_dimensions[row_idx].height = src_ws.row_dimensions[row_idx].height


def apply_body_style(template_ws, dst_ws):
    for row_idx in range(1, dst_ws.max_row + 1):
        template_row = 3 if row_idx >= 3 else row_idx
        for col_idx in range(1, 12):
            src = template_ws.cell(template_row, col_idx)
            dst = dst_ws.cell(row_idx, col_idx)
            if src.has_style:
                dst._style = copy(src._style)
            dst.font = copy(src.font)
            dst.fill = copy(src.fill)
            dst.border = copy(src.border)
            dst.alignment = copy(src.alignment)
            dst.number_format = src.number_format


