    apply_body_style(template, ws)
    for row in ws.iter_rows():
        for cell in row:
            cell.alignment = copy(cell.alignment)
            cell.alignment = cell.alignment.copy(wrap_text=True, vertical="center")
    wb.save(XLSX)
    print(f"Saved {XLSX} with sheet {SHEET_NAME}: {len(rows)} shots, {sum(int(r[1].split('：')[1].replace('秒','')) for r in rows)} seconds")


