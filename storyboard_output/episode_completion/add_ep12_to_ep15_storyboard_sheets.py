def copy_sheet_layout(src_ws, dst_ws):
    for col, dim in src_ws.column_dimensions.items():
        dst_ws.column_dimensions[col].width = dim.width


def apply_style_and_heights(template_ws, dst_ws):
    for row_idx in range(1, dst_ws.max_row + 1):
        template_row = row_idx if row_idx <= template_ws.max_row else 3
        dst_ws.row_dimensions[row_idx].height = (
            template_ws.row_dimensions[row_idx].height
            if row_idx <= template_ws.max_row
            else template_ws.row_dimensions[3].height
        )
        for col_idx in range(1, 12):
            src = template_ws.cell(template_row, col_idx)
            dst = dst_ws.cell(row_idx, col_idx)
            if src.has_style:
                dst._style = copy(src._style)
            dst.font = copy(src.font)
            dst.fill = copy(src.fill)
            dst.border = copy(src.border)
            dst.alignment = copy(src.alignment)
            dst.number_format = src.number_format


def row_from_shot(shot):
    number, duration, size, angle, move, blocking, lighting, content, transition, bgm = shot
    return [
        f"镜头号：{number}",
        f"时长：{duration}秒",
        f"设备/画幅/镜头/光圈：{LENSES[size]}",
        f"景别：{size}",
        f"拍摄视角：{angle}",
        f"运镜：{move}",
        f"全局描写/站位调度：{blocking}",
        f"布光设计：{lighting}",
        content,
        f"转场：{transition}",
        f"BGM：{bgm}",
    ]


def add_episode(source_path: Path, episode: dict) -> Path:
    wb = load_workbook(source_path)
    template = wb["第五集"] if "第五集" in wb.sheetnames else wb[wb.sheetnames[4]]
    sheet_name = episode["sheet"]
    if sheet_name in wb.sheetnames:
        del wb[sheet_name]
    ws = wb.create_sheet(sheet_name)
    copy_sheet_layout(template, ws)
    total_seconds = sum(shot[1] for shot in episode["shots"])
    meta = [
        episode["title"],
        f"本集共{len(episode['shots'])}个镜头，完整时长约为{total_seconds // 60}分{total_seconds % 60}秒",
        "统一设备/画幅：ARRI Alexa Mini LF｜9:16竖画幅",
        "字幕限制：视频中禁止出现任何字幕、标题字、说明字、屏幕文字叠加",
        "音频限制：禁止背景音乐，仅保留角色语音、环境特效音、动作音效",
        "人物面部质感：面部清晰真实，无反光、无油光；自然毛孔感明显，无磨皮涂抹感",
        episode["cast"],
        episode["summary"],
        "",
        "",
        "",
    ]
    ws.append(meta)
    ws.append(HEADERS)
    for shot in episode["shots"]:
        ws.append(row_from_shot(shot))
    apply_style_and_heights(template, ws)
    out_path = ROOT / episode["out"]
    wb.save(out_path)
    print(f"Saved {out_path.name}: {sheet_name}, {len(episode['shots'])} shots, {total_seconds} seconds")
    return out_path


def main() -> None:
    if not BASE.exists():
        raise FileNotFoundError(f"Missing base workbook: {BASE}")
    current = BASE
    for episode in EPISODES:
        current = add_episode(current, episode)


if __name__ == "__main__":
    main()
