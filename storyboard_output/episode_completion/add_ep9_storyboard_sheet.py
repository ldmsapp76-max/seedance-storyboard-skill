def copy_sheet_layout(src_ws, dst_ws):
    for col, dim in src_ws.column_dimensions.items():
        dst_ws.column_dimensions[col].width = dim.width


def apply_style_and_heights(template_ws, dst_ws):
    for row_idx in range(1, dst_ws.max_row + 1):
        if row_idx <= template_ws.max_row:
            dst_ws.row_dimensions[row_idx].height = template_ws.row_dimensions[row_idx].height
        else:
            dst_ws.row_dimensions[row_idx].height = template_ws.row_dimensions[3].height
        template_row = row_idx if row_idx <= template_ws.max_row else 3
        for col_idx in range(1, 12):
            src = template_ws.cell(template_row, col_idx)
            dst = dst_ws.cell(row_idx, col_idx)
            if src.has_style:
                dst._style = copy(src._style)
            dst.font = copy(src.font)
            dst.fill = copy(src.fill)
            dst.border = copy(src.border)
            dst.alignment = copy(src.alignment)
            dst.number_format = src.number_format


def fix_ep8_heights(wb, template_ws):
    if "第8集" not in wb.sheetnames:
        return
    ws = wb["第8集"]
    for row_idx in range(1, ws.max_row + 1):
        if row_idx <= template_ws.max_row:
            ws.row_dimensions[row_idx].height = template_ws.row_dimensions[row_idx].height
        else:
            ws.row_dimensions[row_idx].height = template_ws.row_dimensions[3].height


def main() -> None:
    wb = load_workbook(XLSX)
    template = wb["第五集"] if "第五集" in wb.sheetnames else wb[wb.sheetnames[4]]
    fix_ep8_heights(wb, template)
    if SHEET_NAME in wb.sheetnames:
        del wb[SHEET_NAME]
    ws = wb.create_sheet(SHEET_NAME)
    copy_sheet_layout(template, ws)
    ws.append(meta)
    ws.append(headers)
    for row in rows:
        ws.append(row)
    apply_style_and_heights(template, ws)
    wb.save(XLSX)
    print(f"Saved {XLSX} with fixed 第8集 row heights and sheet {SHEET_NAME}: {len(rows)} shots, {sum(int(r[1].split('：')[1].replace('秒','')) for r in rows)} seconds")


if __name__ == "__main__":
    main()
